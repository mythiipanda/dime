"""Deterministic answer scoring. Stdlib only.

Ports the documented rules from
backend/tests/fixtures/season_consistency_mirror.json (header "rules"),
whose expected values were generated by RUNNING the canonical scorer in
dime-internal. This port is labeled hermetic-fallback wherever it stands
in for the canonical scorer; it cannot detect canonical drift.
"""

from __future__ import annotations

import math
import re

_SEASON_RE = re.compile(r"(20\d\d)\s*[-–—]\s*(\d{2,4})")


def canon_season(raw: str) -> str:
    raw = raw.replace("–", "-").replace("—", "-")
    m = re.match(r"(20\d\d)\s*-\s*(\d{2,4})", raw)
    if not m:
        return raw
    return f"{m.group(1)}-{m.group(2)[-2:]}"


def named_seasons(answer: str) -> set:
    return {canon_season(f"{a}-{b}") for a, b in _SEASON_RE.findall(answer)}


def season_gate_tripped(season: str | None, answer: str) -> bool:
    """True when the answer names a season but never the expected one.

    No season named, or the expected season named among others, is not
    penalized. An explicit wrong-season claim zeroes the score: the
    reported bug class (a 2024-25 question answered with 2025-26
    numbers and phrasing).
    """
    if not season:
        return False
    named = named_seasons(answer)
    return bool(named) and canon_season(season) not in named


def _num_forms(value) -> list[str]:
    """String forms a number may take in prose: 59.1, 59.10, 59%."""
    forms = []
    if isinstance(value, float):
        forms.append(repr(round(value, 4)).rstrip("0").rstrip("."))
        forms.append(f"{value:.1f}")
        forms.append(f"{value:.2f}")
    else:
        forms.append(str(value))
    # percent rendering of a fraction, e.g. 0.591 -> "59.1%"
    if isinstance(value, float) and 0 < abs(value) < 1:
        forms.append(f"{value * 100:.1f}%")
    return forms


def numeric_match(value, answer: str, rel_tol=1e-3) -> bool:
    """True when the answer states the value within tolerance.

    Matches exact numeric forms first (with a trailing-digit guard so
    59.1 does not match inside 159.10), then falls back to parsing
    every number in the answer and comparing within rel_tol.
    """
    for form in _num_forms(value):
        if re.search(r"(?<![\d.])" + re.escape(form) + r"(?![\d.])", answer):
            return True
    try:
        target = float(value)
    except (TypeError, ValueError):
        return False
    for tok in re.findall(r"\d+(?:\.\d+)?%?", answer):
        try:
            cand = float(tok.rstrip("%"))
            if tok.endswith("%"):
                cand /= 100.0
        except ValueError:
            continue
        if math.isclose(cand, target, rel_tol=rel_tol, abs_tol=1e-9):
            return True
    return False


def numeric_acc(facts: dict, answer: str) -> float:
    """1.0 when every numeric fact appears in the answer, else 0.0.

    The season gate zeroes first on an explicit wrong-season claim.
    """
    nums = [v for k, v in facts.items()
            if k != "season" and isinstance(v, (int, float))]
    if not nums:
        return 1.0
    if season_gate_tripped(facts.get("season"), answer):
        return 0.0
    for v in nums:
        if not numeric_match(v, answer):
            return 0.0
    return 1.0


def check_answer(expected: dict, answer: str) -> tuple[bool, str]:
    """Full check for one golden answer.

    expected: {"season": ..., "numbers": [...], "names": [...]}.
    Returns (pass, detail). Empty answers always fail (verify-gate:
    the check is not vacuous).
    """
    if not answer or not answer.strip():
        return False, "empty answer fails by construction (verify-gate)"
    if season_gate_tripped(expected.get("season"), answer):
        return False, (f"wrong-season phrasing: expected "
                       f"{expected.get('season')}, answer names "
                       f"{sorted(named_seasons(answer))}")
    for v in expected.get("numbers", []):
        if not numeric_match(v, answer):
            return False, f"number {v} not found in answer"
    for name in expected.get("names", []):
        if name.lower() not in answer.lower():
            return False, f"name {name!r} not found in answer"
    return True, "all expected numbers/names present"
